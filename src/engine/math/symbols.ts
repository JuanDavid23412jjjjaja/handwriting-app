/**
 * Hand-drawn vector symbols for maths glyphs missing from handwriting fonts
 * (Σ, α, √ radical, arrows…). Coordinates: y grows downward, baseline at 0,
 * glyph height ≈ 0.72 × size. Each entry returns polylines in mm.
 */

type Pt = [number, number];
type Shape = { w: number; strokes: (s: number) => Pt[][] };

function q(p0: Pt, p1: Pt, p2: Pt, n = 10): Pt[] {
  const out: Pt[] = [];
  for (let i = 0; i <= n; i++) {
    const t = i / n;
    const a = (1 - t) * (1 - t);
    const b = 2 * (1 - t) * t;
    const c = t * t;
    out.push([a * p0[0] + b * p1[0] + c * p2[0], a * p0[1] + b * p1[1] + c * p2[1]]);
  }
  return out;
}

function poly(...pts: Pt[]): Pt[] {
  return pts;
}

